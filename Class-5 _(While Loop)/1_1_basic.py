count = 1                        # Initialization: Starting point

while count <= 5:                # Condition: Run the loop until count is 5
    print(f"Welcome to IIT! {count}")  # Action: Print the welcome message with the current count
    count = count + 1            # Update: Increment the count by 1 in each step
    
print(f"Final count: {count}")   # Prints the final value after the loop ends